-- CREATE DATABASE sports;

CREATE TYPE gender AS ENUM ('M', 'W', 'X');
CREATE TYPE host_role AS ENUM ('HOST', 'COHOST', 'MOVED', 'CANCELLED', 'MINE');
CREATE TYPE result_status AS ENUM ('OK', 'HC', 'ANN', 'NR', 'DSQ', 'DNF', 'DNS', 'EXH');
CREATE TYPE stage AS ENUM ('HEAT', 'PLAYIN', 'GROUP_1', 'GROUP_2', 'GROUP_3', 'PLAYOUT', 'PLAYOFF', 'ROUND_OF_32', 'ROUND_OF_16', 'QUARTERFINAL', 'PLACEMENT', 'SEMIFINAL', 'FINAL_GROUP', 'FINAL');
CREATE TYPE discipline_category AS ENUM ('GAME', 'TEAM', 'RELAY', 'INDIVIDUAL');
CREATE TYPE event_type AS ENUM ('OLYMPIC_GAMES', 'OTHER_GAMES', 'CHAMPIONSHIP', 'HIGHER_TOUR', 'LOWER_TOUR');
CREATE TYPE scope AS ENUM ('WORLD', 'INTERCONTINENTAL', 'CONTINENTAL', 'REGIONAL', 'SMALL_STATES', 'NATIONAL', 'NATIONAL_REGIONAL');
CREATE TYPE athletes AS ENUM ('JUNIOR', 'U23', 'SENIOR', 'VETERAN', 'PARA');
CREATE TYPE team_format AS ENUM ('NATIONAL', 'REGIONAL', 'CLUB', 'MIXED', 'OTHER');
CREATE TYPE season AS ENUM ('SUMMER', 'WINTER', 'INDOOR');
CREATE TYPE region AS ENUM ('EUROPE', 'AFRICA', 'ASIA', 'ASIA_PACIFIC', 'OCEANIA', 'AMERICA', 'NORTH_CENTRAL_AMERICA', 'NORTH_AMERICA', 'CENTRAL_AMERICA', 'SOUTH_AMERICA');
CREATE TYPE competition_kind AS ENUM ('OFFICIAL', 'DEMO', 'EXHIBITION');
CREATE TYPE applies_to AS ENUM ('DISCIPLINE_EVENT', 'COUNTRY');
COMMENT ON TYPE host_role IS 'MINE - moje prywatne oznaczenie';
COMMENT ON TYPE applies_to IS 'Decyduje dla jakiej tabeli jest dany tag.code.';

CREATE TABLE country (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	continent region,
	name TEXT NOT NULL UNIQUE,
	path_flag TEXT,
	part_of TEXT,
	status TEXT,
	note TEXT,
	parent_id INTEGER REFERENCES country (id),
	tags VARCHAR(3)[] NOT NULL DEFAULT '{}',
	fed_olympic TEXT,
	fed_football TEXT,
	fed_athletic TEXT,
	fed_other TEXT,
	fed_note TEXT,
	ioc_code VARCHAR(3)
);
COMMENT ON COLUMN country.part_of IS 'Do czego obecnie należy dane terytorium - np: do WB';
COMMENT ON COLUMN country.status IS 'Statusu danego terytorium (albo forma zależności) względem part_of - np: „ter. zależne WB”';
COMMENT ON COLUMN country.tags IS 'Mój prywatny podział zespołów/krajów/państw/regionów.';

CREATE TABLE discipline (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT NOT NULL,
	fed_world TEXT,
	fed_world_old TEXT[],
	fed_world_year SMALLINT,
	fed_europe TEXT,
	fed_europe_old TEXT[],
	fed_europe_year SMALLINT,
	note TEXT,
	UNIQUE (name, fed_world)
);
COMMENT ON TABLE discipline IS 'Para: dyscyplina - federacja światowa nią zarządzająca.';
COMMENT ON COLUMN discipline.name IS 'Nazwa opisowa, popularna, czasem więcej niż jednej naraz, jeśli mają wspólną federację zarządzającą.';
COMMENT ON COLUMN discipline.fed_world IS 'Światowa federacja (skrót) zarządzająca tą dyscypliną.';
COMMENT ON COLUMN discipline.fed_world_old IS 'Poprzednie federacje lub poprzednie skróty nazwy federacji światowej, od pierwszej/najstarszej.';
COMMENT ON COLUMN discipline.fed_world_year IS 'Rok powstania pierwszej federacji światowej.';
COMMENT ON COLUMN discipline.fed_europe IS 'Europejska federacja (skrót) zarządzająca tą dyscypliną.';
COMMENT ON COLUMN discipline.fed_europe_old IS 'Poprzednie federacje lub poprzednie skróty nazwy federacji europejskiej, od pierwszej/najstarszej.';
COMMENT ON COLUMN discipline.fed_europe_year IS 'Rok powstania pierwszej federacji europejskiej.';

CREATE TABLE discipline_event (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	discipline_id INTEGER NOT NULL REFERENCES discipline (id),
	name TEXT NOT NULL,
	category discipline_category NOT NULL,
	season season NOT NULL,
	para BOOLEAN NOT NULL DEFAULT false,
	pictogram bytea,
	tags VARCHAR(3)[] NOT NULL DEFAULT '{}',
	olympic_debut SMALLINT,
	note TEXT,
	UNIQUE (discipline_id, name)
);
COMMENT ON TABLE discipline_event IS 'Konkretne konkurencje (N -> 1) połączone do dyscypliny.';
COMMENT ON COLUMN discipline_event.para IS 'Czy konkurencja paraolimpijska.';
COMMENT ON COLUMN discipline_event.pictogram IS 'Plik SVG z katalogu piktogramy zapisany binarnie w bazie, może być NULL. Import w 2 krokach: COPY bez obrazków, potem osobne wczytanie plików SVG (np. `pg_read_binary_file` albo aplikacja ASP.NET).';
COMMENT ON COLUMN discipline_event.olympic_debut IS 'Rok pierwszego występu na igrzyskach olimpijskich (letnich lub zimowych): oficjalnie albo jako DEMO (pełne rozgrywki wielu reprezentacji), jeśli DEMO było wcześniej lub zamiast. Pokazy EXHIBITION się nie liczą.';
COMMENT ON COLUMN discipline_event.note IS 'Pełna, szczegółowa nazwa / opis (wyświetlana w dymku, nad piktogramem), np. „Piłka nożna (11-osobowa)”; puste = pokazujemy "name".';
COMMENT ON COLUMN discipline_event.tags IS 'Mój prywatny podział konkurencji.';

CREATE TABLE event_series (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name TEXT NOT NULL UNIQUE,
	short TEXT NOT NULL UNIQUE,
	type event_type NOT NULL,
	scope scope NOT NULL,
	region region,
	athletes athletes NOT NULL,
	team_format team_format NOT NULL,
	season season
);
COMMENT ON TABLE event_series IS 'Seria wydarzeń np: IO, ZIO, MŚ, ME.';

CREATE TABLE event (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	series_id INTEGER NOT NULL REFERENCES event_series (id),
	year SMALLINT NOT NULL,
	number SMALLINT,
	ident TEXT,
	note TEXT,
	cancelled boolean NOT NULL DEFAULT false
);
COMMENT ON TABLE event IS 'Konkretne wydarzenie w ramach serii np: IO-24, ZIO-26, MŚ-26, ME-28.';
COMMENT ON COLUMN event.ident IS 'Oficjalna nazwa, gdy inna niż standardowa (np. „Euro 2020”), może być NULL';

CREATE TABLE event_country_role (
	event_id INTEGER REFERENCES event (id),
	country_id INTEGER REFERENCES country (id),
	role host_role NOT NULL,
	cities TEXT[],
	note TEXT,
	PRIMARY KEY (event_id, country_id, role)
);
CREATE UNIQUE INDEX event_country_role_one_host_idx ON event_country_role (event_id) WHERE role = 'HOST';
COMMENT ON TABLE event_country_role IS '1) Ten sam kraj może mieć dwie role (USA 1904: HOST St. Louis & MOVED Chicago). '
	'2) Na jedną imprezę może być tylko jeden HOST. Pilnuje tego: indeks unikalny-częściowy: ON event_country_role (event_id) WHERE role = HOST. '
	'Indeks unikalny na polu: event_id , ale tylko dla wierszy które mają: role = HOST.';
COMMENT ON COLUMN event_country_role.cities IS 'Miasta danego kraju w imprezie, [1] = miasto finału (gdy znane). Braki (brak danych / brak reszty / niepewne) opisane w note.';

CREATE TABLE competition (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	event_id INTEGER NOT NULL REFERENCES event (id),
	discipline_event_id INTEGER NOT NULL REFERENCES discipline_event (id),
	gender gender NOT NULL,
	kind competition_kind NOT NULL DEFAULT 'OFFICIAL',
	note TEXT
);
COMMENT ON COLUMN competition.kind IS 'Status danej konkurencji na zawodach: OFFICIAL -pełnoprawna, DEMO -turniej pokazowy, ale w formie pełnych rozgrywek z wieloma zespołami, '
			'EXHIBITION -typowo pokazowy, przeważnie w formie jednego meczu, lub zawodów tylko drużyn klubowych, regionalnych, uniwersyteckich z jednego lub dwóch państw.';

CREATE TABLE result (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	competition_id INTEGER NOT NULL REFERENCES competition (id),
	country_id INTEGER NOT NULL REFERENCES country (id),
	team_suffix TEXT,
	club_or_team TEXT,
	stage stage,
	place SMALLINT CHECK (place > 0),
	status result_status NOT NULL DEFAULT 'OK',
	score TEXT,
	note TEXT,
	CONSTRAINT result_status_place_not_null CHECK (status <> 'OK' OR place IS NOT NULL),
	CONSTRAINT result_status_place_is_null CHECK (status NOT IN ('NR','DNS','DNF', 'EXH') OR place IS NULL)
);
CREATE UNIQUE INDEX result_one_main_team_idx ON result (competition_id, country_id) WHERE team_suffix IS NULL AND country_id NOT IN (1, 2);
COMMENT ON INDEX result_one_main_team_idx IS 'Najwyżej jedna drużyna główna kraju w konkurencji (team_suffix = NULL, rezerwy mają team_suffix = (2) ), '
											 'ale z wyłączeniem: country_id = 1 (bo to „brak”, czyli nieznane drużyny), lub country_id = 2 (bo to „drużyny mieszane”) '
											 'które mogą się powtarzać. Indeks unikalny częściowy.';
COMMENT ON CONSTRAINT result_status_place_not_null ON result IS 'Wynik OK zawsze ma place.';
COMMENT ON CONSTRAINT result_status_place_is_null ON result IS 'Wynik: NR/DNS/DNF/EXH nigdy nie ma miejsca.';

COMMENT ON TABLE result IS 'Najważniejsza tabela z osiągnięciem danej drużyny. Może to być miejsce, wynik lub jakakolwiek informacja o występie.';

COMMENT ON COLUMN result.team_suffix IS 'Informacja jeśli w zawodach dany zespół/kraj miał więcej niż jedną drużynę, '
										'wtedy oznacza się je jako rezerwy przez dodanie „(2)” dla drugiej i kolejnych drużyn. Jeśli NULL - to jest drużyna główna.';
COMMENT ON COLUMN result.stage IS 'Runda na jakiej zespół ukończył występ.';
COMMENT ON COLUMN result.place IS 'Miejsce w oficjalnej klasyfikacji (result_status = OK), lub osiągnięte poza konkursem (result_status = HC), '
								  'lub osiągnięte i odebrane (result_status = ANN / DSQ), '
								  'NULL jeśli: result_status = NR (NO RESULT: brak wyniku / miejsca / udział bez klasyfikacji) / DNF (nie ukończono) / DNS (nie wystartowano) / EXH (występ totalnie pokazowy, bez miejsca).';
COMMENT ON COLUMN result.score IS 'Czas, wynik decydującego pojedynku, liczba pkt lub medali zł-sr-br (tekst: „37.10”, „3:2”, „74 pkt”, „12-3-5”).';
COMMENT ON COLUMN result.status IS 'Status: OK/HC/ANN/DSQ - Place > 0. Status: NR/DNS/DNF/EXH - Place = NULL.';
COMMENT ON COLUMN result.club_or_team IS 'Jeśli pod szyldem reprezentacji startuje drużyna klubowa, uczelniana, regionalna, inna tego typu, lub reprezentacja pod inną nazwą np.: Francja A, ZSRR II, OAR.';

CREATE TABLE tag (
	applies_to applies_to NOT NULL,
	code VARCHAR(3) NOT NULL,
	short TEXT NOT NULL,
	note TEXT,
	PRIMARY KEY (applies_to, code)
);
COMMENT ON TABLE tag IS 'Tabela dla moich prywatnych podziałów danych z tablic DISCIPLINE_EVENT i COUNTRY.';
